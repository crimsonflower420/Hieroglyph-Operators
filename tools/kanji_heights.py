#!/usr/bin/env python3
"""Per-character operator-tree height for the 2,136 jōyō kanji, using the Kanji in Order tree code.

This script does not define its own kanji trees. It imports the composition rule of the sister repository
(crimsonflower420/Kanji-Morphology, tools/valence_atlas.slots_of, as used by tools/arity_census.py) and reads the
pinned KanjiVG snapshot that repository uses (70a0b7ae, 2026-09-30, CC BY-SA 3.0).

  composition  a KanjiVG group with at least 2 slots (the arity census's definition; 6,176 in this snapshot)
  height       the largest number of compositions on one path from the character's root group to a stroke.
               A character whose groups never have 2 slots has height 0.
               This is the same counting rule as the quadrat height on this site (operator nodes only;
               a step through a one-slot wrapper group adds nothing).
  groupDepth   the arity census's own depth (every nested group adds 1); kept only as a cross-check
               against the census numbers (6,176 compositions, deepest depth 7).

Usage:
  python3 tools/kanji_heights.py --kanji-repo /workspace/kanji/repo [--kanjivg /tmp/kanjivg/.../kanji]
Writes data/kanji-height-reference.json. Exits non-zero if the census totals are not reproduced.
"""
import argparse, json, subprocess, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kanji-repo', type=Path, required=True)
    ap.add_argument('--kanjivg', type=Path, default=None)
    ap.add_argument('--out', type=Path, default=ROOT / 'data' / 'kanji-height-reference.json')
    a = ap.parse_args()
    sys.path.insert(0, str(a.kanji_repo / 'tools'))
    import positions, valence_atlas as va  # noqa: E402  (sister-repo modules)
    kdir = positions.ensure_kanjivg(a.kanjivg)
    joyo = positions.load_joyo()
    if len(joyo) != 2136: sys.exit(f'jōyō list has {len(joyo)} entries')
    sha = subprocess.run(['git', '-C', str(a.kanji_repo), 'rev-parse', '--short', 'HEAD'],
                         capture_output=True, text=True).stdout.strip()

    def height(g):
        slots = va.slots_of(g)
        kids = [c for s in slots for c in s['groups']]
        below = max((height(c) for c in kids), default=0)
        return below + (1 if len(slots) >= 2 else 0)

    comps = 0; gdepth = Counter(); per = {}
    def census(g, d):
        nonlocal comps
        slots = va.slots_of(g)
        if len(slots) >= 2: comps += 1; gdepth[d] += 1
        for s in slots:
            for c in s['groups']: census(c, d + 1)

    for ch in joyo:
        svg = va.parse_svg(kdir / f'{ord(ch):05x}.svg')
        root = va.find_root(svg, ch)
        if root is None: sys.exit(f'no root for {ch}')
        per[ch] = height(root); census(root, 1)
    if comps != 6176 or max(gdepth) != 7:
        sys.exit(f'census not reproduced: {comps} compositions, max group depth {max(gdepth)}')
    dist = Counter(per.values())
    out = {
        '_source': f'KanjiVG snapshot 70a0b7ae0c18ceb5cb358274b029cce0234a43bc (2026-09-30, CC BY-SA 3.0), jōyō list and '
                   f'composition rule (valence_atlas.slots_of) from crimsonflower420/Kanji-Morphology at {sha}. '
                   'Generated by tools/kanji_heights.py.',
        'definition': 'height = largest number of compositions (groups with >= 2 slots) on one root-to-stroke path',
        'chars': len(per), 'compositions': comps, 'groupDepthMax': max(gdepth),
        'height': {str(k): dist[k] for k in sorted(dist)},
        'mean': round(sum(per.values()) / len(per), 3),
        'perChar': per,
    }
    a.out.write_text(json.dumps(out, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
    print('kanji heights', out['height'], 'mean', out['mean'], 'compositions', comps)

if __name__ == '__main__':
    main()
